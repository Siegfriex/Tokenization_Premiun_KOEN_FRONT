/**
 * Renders the human-readable ledgers from docs/audit/data/trace-ledger.json.
 *
 *   node docs/audit/tools/render-docs.mjs
 *
 * Writes:
 *   docs/audit/TRACE_LEDGER.md        master, every tracked node, grouped by widget
 *   docs/audit/NUMERIC_CLAIMS.md      every rendered number + its dispute status
 *   docs/audit/SEMANTIC_DOM.md        dl / ul / figure / nav / heading gaps
 *   docs/audit/STABLE_HOOKS.md        addressing today + the data-* hook each node needs
 *   docs/audit/DESIGN_APPLICATION.md  typography / colour / layout roles per node
 *
 * Prose docs (README, REMEDIATION_BATCHES, DIRECTOR_DECISIONS) are authored by
 * hand and reference these by Trace ID.
 */
import fs from 'node:fs';
import path from 'node:path';

const ROOT = process.cwd();
const DOCS = path.join(ROOT, 'docs/audit');
const { items } = JSON.parse(fs.readFileSync(path.join(DOCS, 'data/trace-ledger.json'), 'utf8'));
const live = items.filter((i) => !i.deadFile);
const dead = items.filter((i) => i.deadFile);

const esc = (s) => String(s ?? '').replace(/\|/g, '\\|').replace(/\n/g, ' ');
const trunc = (s, n) => { const t = String(s ?? ''); return t.length > n ? t.slice(0, n - 1) + '…' : t; };
const groupBy = (arr, fn) => arr.reduce((m, i) => ((m[fn(i)] ??= []).push(i), m), {});
const HDR = (title, blurb) => `# ${title}\n\n> Generated by \`docs/audit/tools/render-docs.mjs\` from\n> \`docs/audit/data/trace-ledger.json\`. Do not hand-edit — re-run the tools.\n> Every row is addressable by its Trace ID from any other ledger.\n\n${blurb}\n`;

/* ============================== MASTER ============================== */
{
  const byWidget = groupBy(live, (i) => i.widget);
  const order = ['StoryProgress','NewsHeroSection','TokenCompareSection','PipelineSection','TokenPremiumSection','OccupationSection','MultilingualTokenEfficiencySection','KoreaAIContextSection','ImpactSection','MethodSection','EditorialConclusionSection','Footer','ArticleElements','App','LanguageSwitch','SelectableCard','TokenChip','SectionHeading','Container','Section','Stack','Cluster','Divider'];
  const names = [...new Set([...order.filter((w) => byWidget[w]), ...Object.keys(byWidget)])];

  let md = HDR('Master Trace Ledger',
`Every content-bearing or structure-bearing node in the rendered frontend.
A node enters this ledger if it renders a literal, asserts a number, has a
semantic-structure gap, or is a section root.

**${live.length}** live items across **${names.length}** rendering units, plus
**${dead.length}** items in \`MultilingualSection.tsx\` (dead file, listed
separately at the end so it never inflates a count).

Columns: **Addr** = how the node can be targeted today
(\`STYLE_SIGNATURE\` = only by its Tailwind class string, so any design change
breaks the selector; \`NTH_CHILD_ONLY\` = not even that, only by sibling
position). **Cat** = primary category. **Batch** = the coordinated remediation
group this belongs to (see \`REMEDIATION_BATCHES.md\`).`);

  for (const w of names) {
    const rows = byWidget[w];
    const sect = rows[0].section;
    md += `\n## ${w}\n\n_${sect} · ${rows[0].file} · ${rows.length} tracked nodes_\n\n`;
    md += '| Trace ID | Lines | DOM | Cat | Addr | Literal / role | Gap | Risk | Batch |\n|---|---|---|---|---|---|---|---|---|\n';
    for (const i of rows) {
      const label = i.literal ? trunc(i.literal, 68) : `_(${i.jsxTag})_`;
      md += `| \`${i.traceId}\` | ${i.lines} | \`${i.domTag}\` | ${i.primaryCategory.replace('_', ' ')} | ${i.addressing.replace('STYLE_SIGNATURE','style').replace('NTH_CHILD_ONLY','nth-child').replace('STABLE (id)','id')} | ${esc(label)} | ${i.semanticGap ?? '—'} | ${i.risk} | ${i.batch} |\n`;
    }
  }

  md += `\n## MultilingualSection.tsx — dead file\n\nNot imported anywhere, never rendered. Tracked so it is not silently forgotten, excluded from every live count. ${dead.length} nodes. Deletion is batch **B6** and requires an explicit decision.\n`;
  fs.writeFileSync(path.join(DOCS, 'TRACE_LEDGER.md'), md);
}

/* ========================== NUMERIC CLAIMS ========================== */
{
  const nc = live.filter((i) => i.numericClaims.length);
  const disputed = nc.filter((i) => i.mismatchStatus.startsWith('CONTRADICTED'));
  const duplicated = nc.filter((i) => i.mismatchStatus.startsWith('DUPLICATED'));
  const unlinked = nc.filter((i) => i.mismatchStatus.startsWith('UNLINKED') && !i.mismatchStatus.includes('coincides'));
  const present = nc.filter((i) => i.mismatchStatus.startsWith('VALUE_PRESENT'));
  const coincident = nc.filter((i) => i.mismatchStatus.includes('coincides'));

  let md = HDR('Numeric Claim Ledger',
`Every number the site renders as a claim about the research: ratios, token
counts, percentages, corpus sizes, benchmark counts, ranges.

**Nothing here is resolved.** Every disputed value is FROZEN pending a
Director decision. No replacement value has been derived, and no explanation
for a mismatch has been invented — each row states only what the markup
renders and what the entity data holds.

Tokenizer names (\`o200k_base\`), corpus names (\`Flores-200\`), figure numbers
(\`FIG. 01\`) and years are traced separately as identifiers, not claims.

| Status | Count | Meaning |
|---|---|---|
| CONTRADICTED — FROZEN | ${disputed.length} | markup and entity data do not agree, or the markup asserts something the data cannot support |
| DUPLICATED | ${duplicated.length} | the value agrees with an entity, but the markup hardcodes its own copy — free to drift |
| UNLINKED | ${unlinked.length} | no entity anywhere holds this value; the number exists only in markup |
| VALUE_PRESENT | ${present.length} | an entity does hold this value, but the markup hardcodes it rather than reading it |
| UNLINKED (count coincidence) | ${coincident.length} | a rendered count happens to equal the array length today, but is not read from it — free to drift silently |`);

  const sec = (title, rows, extra) => {
    md += `\n## ${title} (${rows.length})\n\n`;
    if (!rows.length) { md += '_none_\n'; return; }
    md += `| Trace ID | Widget | Lines | Rendered | ${extra} |\n|---|---|---|---|---|\n`;
    for (const i of rows) {
      const vals = i.numericClaims.map((c) => `\`${c.value}\``).join(' ');
      const note = i.contradiction
        ? `**observed:** ${esc(i.contradiction.observed)}<br>**entity:** ${esc(i.contradiction.entity)}`
        : i.entityLinkedValues.length
          ? esc(i.entityLinkedValues.map((e) => `${e.value} also at ${e.at.join(', ')}`).join('; '))
          : i.countCheck ? esc(i.countCheck)
          : '_no entity holds this value_';
      md += `| \`${i.traceId}\` | ${i.widget} | ${i.lines} | ${esc(trunc(i.literal, 60))} ${vals} | ${note} |\n`;
    }
  };
  sec('CONTRADICTED — frozen pending Director decision', disputed, 'Observation');
  sec('DUPLICATED — value agrees today, but markup owns its own copy', duplicated, 'Observation');
  sec('UNLINKED — value exists only in markup', unlinked, 'Note');
  sec('VALUE_PRESENT in an entity, but hardcoded in markup', present, 'Entity location');
  sec('UNLINKED — count coincides with an array length but is not read from it', coincident, 'Check');
  fs.writeFileSync(path.join(DOCS, 'NUMERIC_CLAIMS.md'), md);
}

/* =========================== SEMANTIC DOM =========================== */
{
  const gaps = live.filter((i) => i.semanticGap);
  const byGap = groupBy(gaps, (i) => i.semanticGap);
  const TITLES = {
    LIST: 'Collections rendered as anonymous siblings — need `<ul>` / `<li>`',
    DL_PAIR: 'Term/value pairs rendered as anonymous boxes — need `<dl>` / `<dt>` / `<dd>`',
    FIGURE: 'Chart captions with no tie to their chart — need `<figure>` / `<figcaption>`',
    NAV_LIST: 'Navigation without an accessible name or list structure',
    LABEL_ORPHAN: 'Labels with no programmatic relationship to what they label',
    HEADING_LEVEL: 'Headings whose level is set per widget with no document-wide outline',
  };
  let md = HDR('Semantic DOM Ledger',
`Where the rendered DOM fails to express the structure of the data it is
showing. Every one of these is why a node can only be reached today by a
style signature or a sibling index.

None of this is changed in this phase. This ledger defines batch **B3**.

| Gap | Count |
|---|---|
${Object.entries(byGap).map(([k, v]) => `| ${k} | ${v.length} |`).join('\n')}`);

  for (const [gap, rows] of Object.entries(byGap)) {
    md += `\n## ${gap} — ${TITLES[gap] ?? ''} (${rows.length})\n\n`;
    md += `_${esc(rows[0].semanticWhy)}_\n\n`;
    md += '| Trace ID | Widget | Lines | Current DOM | Collection / literal | Recommended structure |\n|---|---|---|---|---|---|\n';
    for (const i of rows) {
      md += `| \`${i.traceId}\` | ${i.widget} | ${i.lines} | \`${i.domTag}\` | ${esc(trunc(i.mapOver ?? i.literal, 54))} | ${esc(i.recommendedSemantics)} |\n`;
    }
  }
  fs.writeFileSync(path.join(DOCS, 'SEMANTIC_DOM.md'), md);
}

/* =========================== STABLE HOOKS =========================== */
{
  const byAddr = groupBy(live, (i) => i.addressing);
  const needing = live.filter((i) => i.recommendedHook);
  const byHook = groupBy(needing, (i) => i.recommendedHook.split(' ')[0]);

  let md = HDR('Stable Hook Ledger',
`How each tracked node can be addressed **today**, and the stable
style-independent hook it needs so that it can be addressed **after** a
redesign.

This is the ledger that makes the rest possible. Today a QA assertion, an
analytics selector, a deep link, or a bug report can only name a node by its
Tailwind class string or its position among siblings — so the selector *is*
the styling, and every design change silently invalidates it.

| Addressing today | Count | Consequence |
|---|---|---|
| STYLE_SIGNATURE | ${(byAddr['STYLE_SIGNATURE'] ?? []).length} | selector breaks when the design changes |
| NTH_CHILD_ONLY | ${(byAddr['NTH_CHILD_ONLY'] ?? []).length} | selector breaks when content is added or reordered |
| STABLE (id) | ${(byAddr['STABLE (id)'] ?? []).length} | the ten section anchors, and nothing below them |
| STABLE (data-*) | ${(byAddr['STABLE (data-*)'] ?? []).length} | — |

**Zero \`data-*\` attributes exist in the codebase today.**

## Proposed hook vocabulary

| Hook | Applies to | Count |
|---|---|---|
${Object.entries(byHook).sort((a, b) => b[1].length - a[1].length).map(([k, v]) => `| \`${k}\` | ${v[0].primaryCategory} nodes | ${v.length} |`).join('\n')}`);

  md += `\n## Per-node hook assignment\n\n| Trace ID | Widget | Lines | DOM | Addressing today | Current locator | Recommended hook |\n|---|---|---|---|---|---|---|\n`;
  for (const i of needing) {
    md += `| \`${i.traceId}\` | ${i.widget} | ${i.lines} | \`${i.domTag}\` | ${i.addressing} | \`${esc(trunc(i.locator, 60))}\` | \`${esc(i.recommendedHook)}\` |\n`;
  }
  fs.writeFileSync(path.join(DOCS, 'STABLE_HOOKS.md'), md);
}

